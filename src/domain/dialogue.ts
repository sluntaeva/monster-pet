// Each pet/event has its own rotation; adjacent reactions never repeat a line.
const positions = new Map<string, number>();
export function petLine(kind: PetKind, event: LineEvent): string {
  const lines = dialogue[kind][event];
  const key = `${kind}:${event}`;
  const index = positions.get(key) ?? 0;
  positions.set(key, (index + 1) % lines.length);
  return lines[index];
}
export function touchLine(pet: PetState): string {
  const event = pet.satiety < 30 ? 'hungry' : pet.energy < 30 ? 'tired' : pet.mood < 30 ? 'grumpy' : 'touch';
  return petLine(pet.kind, event);
}
